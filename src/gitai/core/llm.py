def _extract_json(text: str) -> dict:
    """
    Extract and parse JSON from LLM response text.
    
    LLM responses often include markdown formatting (code fences) around
    JSON output. This function strips those markers and parses the content.
    
    Args:
        text (str): Raw text response from the LLM, potentially containing
            markdown code fences like ```json ... ```
    
    Returns:
        dict: Parsed JSON content as a Python dictionary
    
    Raises:
        json.JSONDecodeError: If the cleaned text is not valid JSON
        ValueError: If the text cannot be parsed after cleanup
    
    Example:
        >>> response = '```json\\n{"message": "fix: bug"}\\n```'
        >>> _extract_json(response)
        {'message': 'fix: bug'}
    """
    # Remove markdown code fences (``` or ```json) and strip whitespace
    text = re.sub(r"```(?:json)?", "", text).strip().strip("`").strip()
    return json.loads(text)


def _is_truncated(text: str) -> bool:
    """
    Detect if the LLM response appears to be truncated.
    
    Checks for common signs of truncation:
    - Text ends with incomplete sentence (no punctuation)
    - Text ends with incomplete JSON (missing closing braces/brackets)
    - Text ends with ellipsis or cut-off words
    
    Args:
        text (str): The text to check for truncation
        
    Returns:
        bool: True if the text appears to be truncated
    """
    if not text or len(text) < 10:
        return False
    
    text = text.strip()
    
    # Check if text ends with incomplete JSON
    # Count opening and closing braces/brackets
    open_braces = text.count('{')
    close_braces = text.count('}')
    open_brackets = text.count('[')
    close_brackets = text.count(']')
    
    if open_braces > close_braces or open_brackets > close_brackets:
        return True
    
    # Check if text ends without proper punctuation (for non-JSON responses)
    if not text.endswith(('.', '!', '?', '"', "'", '`', '\n')):
        # Additional check: if it ends mid-word (no space before end)
        if len(text) > 20 and not text[-20:].endswith(('."', '."', '."', '```')):
            return True
    
    # Check for common truncation patterns
    truncation_patterns = [
        r'\.\.\.+$',  # Ends with ellipsis
        r'—$',  # Ends with em dash
        r'[a-zA-Z]$',  # Ends with a letter (likely mid-word)
    ]
    
    for pattern in truncation_patterns:
        if re.search(pattern, text):
            return True
    
    return False


